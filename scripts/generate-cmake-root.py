"""generate-cmake-root.py — writes the root CMakeLists.txt from what the tree contains.

The domino: symonlearn -> symonbake -> bitbake -> recipe (inherit cmake) -> CMakeLists.txt.
Every first-party runtime with native code carries its own work/runtimes/<rt>/app/
CMakeLists.txt; this file is the one above them that says what the PROJECT is. It is
discovered, not listed: a runtime that gains a CMakeLists.txt appears here on the next run.

Two consumers:
  * a developer:  cmake -S . -B work/output/cmake && cmake --build work/output/cmake
                  builds every first-party native target against the host toolchain
  * bitbake:      each recipe still builds its own subtree through symoneural-firstparty;
                  the root exists so the project is one thing, not N unrelated ones

  python3 scripts/generate-cmake-root.py [--check]
"""
import argparse, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def runtimes_with_cmake():
    out = []
    base = os.path.join(ROOT, "work", "runtimes")
    for rt in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        p = os.path.join(base, rt, "app", "CMakeLists.txt")
        if os.path.isfile(p):
            src = open(p).read()
            m = re.search(r"project\((\S+)\s+VERSION\s+([\d.]+)", src)
            out.append((rt, m.group(1) if m else rt, m.group(2) if m else "0.0.0"))
    return out

def render(rts):
    o = ["# SymonSayLearn — root CMakeLists.txt",
         "# GENERATED by scripts/generate-cmake-root.py from work/runtimes/*/app/CMakeLists.txt.",
         "# Do not edit; add a CMakeLists.txt to a runtime and regenerate (symon generate-cmake-root).",
         "#",
         "# This is the end of the chain symonlearn -> symonbake -> bitbake -> recipe -> cmake.",
         "# Each runtime below is also built on its own by its recipe (symoneural-firstparty +",
         "# cmake); this file is what makes them one project for a developer's cmake run.",
         "cmake_minimum_required(VERSION 3.20)",
         "project(SymonSayLearn LANGUAGES C)", "",
         "# Build output stays out of the portals. Each runtime's host build lands in",
         "# work/output/<rt>/host, beside its bitbake output - cmake is a FILE here, not a folder.",
         'if(CMAKE_BINARY_DIR STREQUAL CMAKE_SOURCE_DIR)',
         '  message(FATAL_ERROR "in-source builds are not allowed; use -B work/output/host")',
         "endif()", "",
         "option(SYMON_BUILD_TESTS \"build each runtime's native tests\" OFF)", ""]
    o += ["# A runtime that links ESTATE libraries (pkg_check_modules in its CMakeLists) can only",
          "# build where those exist: a bitbake sysroot. On the host it is reported and skipped,",
          "# never failed - the host has no libllama and must not be given one.",
          "find_package(PkgConfig QUIET)", ""]
    for rt, name, ver in rts:
        src = open(os.path.join(ROOT, "work", "runtimes", rt, "app", "CMakeLists.txt")).read()
        mods = re.findall(r"pkg_check_modules\(\w+\s+REQUIRED\s+(?:IMPORTED_TARGET\s+)?(\w+)", src)
        o.append("# %-10s %-18s %s" % (rt, name, ver))
        if mods:
            for m in mods:
                o.append("pkg_check_modules(_SYM_HAVE_%s QUIET %s)" % (m, m))
            o.append("if(%s)" % " AND ".join("_SYM_HAVE_%s_FOUND" % m for m in mods))
            o.append("  add_subdirectory(work/runtimes/%s/app ${CMAKE_SOURCE_DIR}/work/output/%s/host)" % (rt, rt))
            o.append("else()")
            o.append('  message(STATUS "%s: needs estate package(s) %s - built by bitbake only, skipped here")' % (rt, ", ".join(mods)))
            o.append("endif()")
        else:
            o.append("add_subdirectory(work/runtimes/%s/app ${CMAKE_SOURCE_DIR}/work/output/%s/host)" % (rt, rt))
    o += ["", "# Runtimes with no native code (Python, recipes only) are built by bitbake alone:",
          "#   " + " ".join(sorted(set(os.listdir(os.path.join(ROOT, "work", "runtimes"))) - {r for r, _, _ in rts})), ""]
    return "\n".join(o)

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args()
    rts = runtimes_with_cmake(); body = render(rts); p = os.path.join(ROOT, "CMakeLists.txt")
    cur = open(p).read() if os.path.exists(p) else None
    if a.check:
        print("stale" if cur != body else "current"); sys.exit(1 if cur != body else 0)
    open(p, "w").write(body)
    print("CMakeLists.txt: %d native runtimes -> %s" % (len(rts), ", ".join(r for r, _, _ in rts)))

main()
