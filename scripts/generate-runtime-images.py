"""generate-runtime-images.py — one packagegroup + one proof image per runtime, from its recipes.

scripts -> source. A runtime's deployable surface is the set of recipes in
work/recipes/recipes-<rt>/ minus anything already grouped by hand (image recipes, native
-dev splits, packagegroups). This writes:

  work/recipes/recipes-core/packagegroups/packagegroup-symoneural-<rt>.bb
  work/recipes/recipes-core/images/symoneural-image-<rt>.bb

for every runtime that has recipes and no hand-written group yet, and leaves any existing
one alone - api, cli, common, ravencalc, llm, diffuse were curated by hand and know things
this generator cannot (dlopen modules, python3 for the harness). Idempotent.

  python3 scripts/generate-runtime-images.py [--check]
"""
import argparse, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECIPES = os.path.join(ROOT, "work", "recipes")
PG_DIR = os.path.join(RECIPES, "recipes-core", "packagegroups")
IMG_DIR = os.path.join(RECIPES, "recipes-core", "images")

def recipes_for(rt):
    d = os.path.join(RECIPES, "recipes-" + rt)
    pns = []
    for pn in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if not os.path.isdir(os.path.join(d, pn)): continue
        bbs = [f for f in os.listdir(os.path.join(d, pn)) if f.endswith(".bb")]
        if not bbs: continue
        txt = open(os.path.join(d, pn, bbs[0])).read()
        if "inherit image" in txt or "inherit packagegroup" in txt: continue
        # -native / -dev-only / reference-only recipes are not a runtime surface
        if re.search(r'^SYMON_ALLOW_EMPTY_D\s*=\s*"1"', txt, re.M): continue
        pns.append(pn)
    return pns

PG = '''# The deployable {rt} runtime surface: every recipe in work/recipes/recipes-{rt}/ that
# produces a package. GENERATED by scripts/generate-runtime-images.py from that directory;
# a recipe added there appears here on the next run. Models and weights are never here.
SUMMARY = "SyMoNeuRaL {rt} runtime"
LICENSE = "MIT"
inherit packagegroup

RDEPENDS:${{PN}} = " \\
{deps}
"
'''

IMG = '''# Clean-target proof image for the {rt} runtime: a rootfs assembled by opkg from the
# package feed containing packagegroup-symoneural-{rt} and its RDEPENDS. No source tree,
# no devtool workspace, no pip, no build frontends, no weights.
# GENERATED by scripts/generate-runtime-images.py.
#
# python3-modules is for the HARNESS: work/tools/clean-root-proof runs a Python proof body
# under the target loader and refuses a root without an interpreter. It is not part of the
# {rt} surface; the manifest's symoneural-* rows are.
SUMMARY = "SyMoNeuRaL {rt} clean-root proof image"
LICENSE = "MIT"

inherit image

IMAGE_INSTALL = "packagegroup-symoneural-{rt} python3-modules"
IMAGE_FEATURES = ""
IMAGE_LINGUAS = ""
IMAGE_FSTYPES = "tar.gz"
IMAGE_INSTALL:remove = "packagegroup-core-boot"
NO_RECOMMENDATIONS = "1"
# no qemuboot and no kernel: nothing boots this tarball (see symoneural-image-api)
IMAGE_CLASSES:remove = "qemuboot"
KERNEL_DEPLOY_DEPEND = ""
KERNELDEPMODDEPEND = ""
'''

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args()
    written, kept = [], []
    for d in sorted(os.listdir(RECIPES)):
        if not d.startswith("recipes-") or d == "recipes-core": continue
        rt = d[len("recipes-"):]
        # only RUNTIMES get a deployable surface: a group with no upstream/<rt>/ is a
        # supporting recipe set (cuda, devtools, platform) that other runtimes consume
        if not os.path.isdir(os.path.join(ROOT, "upstream", rt)): continue
        pns = recipes_for(rt)
        if not pns: continue
        pg = os.path.join(PG_DIR, "packagegroup-symoneural-%s.bb" % rt)
        img = os.path.join(IMG_DIR, "symoneural-image-%s.bb" % rt)
        for path, body in ((pg, PG.format(rt=rt, deps="\n".join("    %s \\" % p for p in pns))),
                           (img, IMG.format(rt=rt))):
            if os.path.exists(path) and "GENERATED by scripts/generate-runtime-images.py" not in open(path).read():
                kept.append(os.path.relpath(path, ROOT)); continue        # hand-curated: never overwrite
            cur = open(path).read() if os.path.exists(path) else None
            if cur != body:
                written.append(os.path.relpath(path, ROOT))
                if not a.check: open(path, "w").write(body)
    if a.check:
        print("stale:", written or "none"); sys.exit(1 if written else 0)
    print("written %d:" % len(written)); [print("  ", w) for w in written]
    print("kept (hand-curated) %d" % len(kept))

main()
